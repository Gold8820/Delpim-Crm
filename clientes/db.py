# Colunas adicionadas depois da primeira versão. Em bancos novos já vêm no CREATE TABLE;
# o ADD COLUMN IF NOT EXISTS garante o mesmo resultado em qualquer banco existente.
_ADDITIONS = {
    "importacoes": {
        "arquivo_contratos": "TEXT",
        "contratos_gravados": "INTEGER NOT NULL DEFAULT 0",
        "contratos_rejeitados": "INTEGER NOT NULL DEFAULT 0",
    },
    "clientes": {"observacoes": "TEXT"},
    "contratos": {"observacoes": "TEXT"},
}


class Row(dict):
    """Linha do resultado, igual ao antigo sqlite3.Row:
    - row["codigo"] acessa pelo nome; row[0] acessa pela posição;
    - iterar (for a, b in row / tuple(row) / list(row)) percorre os VALORES, não as chaves.
    dict(row) e **row continuam usando as chaves (keys()).
    """

    def __getitem__(self, key):
        if isinstance(key, int):
            return list(self.values())[key]
        return super().__getitem__(key)

    def __iter__(self):
        return iter(self.values())


def _row_factory(cursor):
    if cursor.description is None:  # comando sem resultado (DDL, UPDATE sem RETURNING)
        return lambda values: Row(zip((), values))
    names = [column.name for column in cursor.description]

    def make(values):
        return Row(zip(names, values))

    return make


def connect(url: str, schema: str | None = None) -> psycopg.Connection:
    """Abre uma conexão. `schema` só é usado pelos testes (cada teste tem o seu schema isolado)."""
    extra = {"options": f"-c search_path={schema},public,extensions"} if schema else {}
    # prepare_threshold=None: sem prepared statements no servidor. O pooler do Supabase (modo transação)
    # não os mantém entre conexões; desligar evita erros do tipo 'prepared statement does not exist'.
    return psycopg.connect(url, row_factory=_row_factory, prepare_threshold=None, **extra)


def _migrate(conn: psycopg.Connection) -> None:
    """Acrescenta colunas que faltam, sem apagar nada."""
    for table, additions in _ADDITIONS.items():
        for name, ddl in additions.items():
            conn.execute(f"ALTER TABLE {table} ADD COLUMN IF NOT EXISTS {name} {ddl}")


def _ensure_unaccent(conn: psycopg.Connection) -> None:
    """A ordenação e a busca por nome usam unaccent(). Tenta criar a extensão uma vez."""
    try:
        conn.execute("CREATE EXTENSION IF NOT EXISTS unaccent")
    except psycopg.Error:
        conn.rollback()
        log.warning("Não foi possível criar a extensão 'unaccent'. Peça ao administrador do banco "
                    "para executar: CREATE EXTENSION IF NOT EXISTS unaccent;")


def _seed_curvas(conn: psycopg.Connection) -> None:
    """Cria as faixas da Curva ABC com os valores iniciais, somente se a tabela estiver vazia."""
    from .classification import VALORES_INICIAIS
    from .repository import now

    if conn.execute("SELECT COUNT(*) FROM curvas_abc").fetchone()[0]:
        return
    stamp = now()
    with conn.cursor() as cur:
        cur.executemany(
            "INSERT INTO curvas_abc (classificacao, minimo_centavos, maximo_centavos, atualizado_em) "
            "VALUES (%s, %s, %s, %s)",
            [(label, minimo, maximo, stamp) for label, minimo, maximo in VALORES_INICIAIS])


def init_db(url: str, schema: str | None = None) -> None:
    """Cria/atualiza as tabelas. Seguro de chamar várias vezes (idempotente)."""
    conn = connect(url, schema)
    try:
        # Trava de sessão: evita que duas instâncias inicializem o banco ao mesmo tempo.
        conn.execute("SELECT pg_advisory_xact_lock(hashtext('clientes-init'))")
        if schema:
            conn.execute(f"CREATE SCHEMA IF NOT EXISTS {schema}")
        for statement in SCHEMA:
            conn.execute(statement)
        _migrate(conn)
        _seed_curvas(conn)
        conn.commit()
        _ensure_unaccent(conn)
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()


def get_db() -> psycopg.Connection:
    if "db" not in g:
        g.db = connect(current_app.config["DATABASE_URL"], current_app.config.get("DB_SCHEMA"))
    return g.db


def close_db(_exc=None) -> None:
    db = g.pop("db", None)
    if db is not None:
        db.close()
